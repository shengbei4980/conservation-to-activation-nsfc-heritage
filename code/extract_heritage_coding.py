def load_nsfc_results_csv(path: Path) -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    result: dict[str, dict[str, str]] = {}
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            approval_no = (row.get("approval_no") or "").strip()
            if approval_no and approval_no not in result:
                result[approval_no] = {k: (v or "").strip() for k, v in row.items()}
    return result


def load_achievement_stat_csv(path: Path) -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    stats: dict[str, dict[str, str]] = {}
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = set(reader.fieldnames or [])
        is_long_table = {"approval_no", "stat_item", "stat_value"}.issubset(fieldnames)
        for row in reader:
            approval_no = (row.get("approval_no") or "").strip()
            if not approval_no:
                continue
            if is_long_table:
                item = (row.get("stat_item") or "").strip()
                value = (row.get("stat_value") or "").strip()
                if item:
                    stats.setdefault(approval_no, {})[item] = value
            else:
                for item in ACHIEVEMENT_STAT_COLUMNS:
                    if item in fieldnames:
                        value = (row.get(item) or "").strip()
                        stats.setdefault(approval_no, {})[item] = value
    return stats


