def clean_text(text: str) -> str:
    """清洗 HTML、Markdown 图片、过密空白，保留语义文本。"""
    if not text:
        return ""

    text = html.unescape(text)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[\u200b-\u200f\ufeff]", "", text)
    text = text.replace("\x0c", "\n")

    # 删除脚本、样式、图片标签与 Markdown 图片；普通 Markdown 链接保留可读文本。
    text = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", " ", text, flags=re.IGNORECASE | re.DOTALL)
    text = re.sub(r"<img\b[^>]*>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", " ", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)

    # HTML 结构标签转为换行或空格，保留表格单元格里的语义文本。
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"</(p|div|section|article|h\d|li|tr|table)>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"</(td|th)>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"<[^>]+>", " ", text)

    # 删除 LaTeX 过密符号的一部分，但不强行改写中文语义
    text = text.replace("\\quad", " ").replace("\\mathrm", " ")
    text = re.sub(r"^#{1,6}\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$", " ", text, flags=re.MULTILINE)

    # 合并过密空白，同时保留自然段；修复 OCR 中常见的中文断字空格。
    text = re.sub(r"[ \t\u00a0]+", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    text = re.sub(r"(?<=[\u4e00-\u9fff]) (?=[\u4e00-\u9fff])", "", text)
    text = re.sub(r"(?<=[\u4e00-\u9fff]) (?=[，。！？；：、）】》])", "", text)
    text = re.sub(r"(?<=[（【《]) (?=[\u4e00-\u9fff])", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


def limit_text(text: str, max_chars: int = MAX_PROJECT_CHARS) -> str:
    """清洗后尽量保留全文；仅在超过上限时做尾部截断。"""
    text = clean_text(text)
    if len(text) <= max_chars:
        return text

    marker = "\n\n【说明：清洗后的全文仍超过MAX_PROJECT_CHARS，已按字符上限截断尾部。】"
    keep_chars = max(0, max_chars - len(marker))
    return text[:keep_chars].rstrip() + marker


def read_project_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8", errors="replace") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise ValueError(f"{path} 顶层不是JSON对象")
    return data


def build_project_text(
    json_path: Path,
    project_json: dict[str, Any],
    nsfc_meta: dict[str, dict[str, str]] | None = None,
    achievement_stats: dict[str, dict[str, str]] | None = None,
    max_chars: int = MAX_PROJECT_CHARS,
) -> str:
    approval_no = str(project_json.get("report_id") or json_path.stem.replace("_llm_ready", ""))
    meta = (nsfc_meta or {}).get(approval_no, {})
    stats = (achievement_stats or {}).get(approval_no, {})

    metadata_lines = [
        f"文件名: {json_path.name}",
        f"report_id/approval_no: {approval_no}",
        f"total_pages: {project_json.get('total_pages')}",
    ]

    for key in [
        "approval_no",
        "project_name",
        "search_category",
        "search_code",
        "apply_code",
        "pi_name",
        "org_name",
        "research_period_start",
        "research_period_end",
        "funding_amount",
        "funding_unit",
        "project_abstract_cn",
        "project_abstract_en",
        "final_abstract_cn",
        "final_abstract_en",
    ]:
        value = meta.get(key)
        if value:
            metadata_lines.append(f"{key}: {value}")

    if stats:
        stat_text = "; ".join(f"{k}: {v}" for k, v in stats.items() if v not in ("", None))
        if stat_text:
            metadata_lines.append(f"achievement_stats: {stat_text}")

    report_text = str(project_json.get("project_full_markdown") or "")
    report_text = limit_text(report_text, max_chars=max_chars)

    return "\n".join(
        [
            "【项目元数据】",
            "\n".join(metadata_lines),
            "\n【结题报告/OCR全文清洗文本】",
            report_text,
        ]
    )


