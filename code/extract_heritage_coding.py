def normalize_label(field: str, value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        items = value
    else:
        items = [value]

    allowed = ALLOWED_LABELS.get(field)
    aliases = LABEL_ALIASES.get(field, {})
    normalized: list[str] = []
    for item in items:
        text = str(item).strip()
        if not text:
            continue
        mapped = aliases.get(text, text)
        mapped_items = mapped if isinstance(mapped, list) else [mapped]
        for mapped_item in mapped_items:
            label = str(mapped_item).strip()
            if allowed is None or label in allowed:
                normalized.append(label)

    deduped = list(dict.fromkeys(normalized))
    if field in ARRAY_FIELDS:
        if not deduped and field in FIELD_FALLBACKS:
            return [FIELD_FALLBACKS[field]]
        if len(deduped) > 1 and "信息不足" in deduped:
            deduped = [x for x in deduped if x != "信息不足"]
        return deduped

    if deduped:
        return [deduped[0]]
    fallback = FIELD_FALLBACKS.get(field)
    return [fallback] if fallback else []


def has_specific_tags(field: str, values: Any) -> bool:
    """判断多标签字段是否已有可分析标签，而不是只有兜底标签。"""
    if not isinstance(values, list) or not values:
        return False
    fallback = FIELD_FALLBACKS.get(field)
    return any(v != fallback for v in values)


