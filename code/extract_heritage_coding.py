def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="NSFC遗产研究议程LLM框架化变量提取")
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_INPUT_DIR, help="*_llm_ready.json所在目录")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR, help="输出目录")
    parser.add_argument("--glob", default="*_llm_ready.json", help="输入文件通配符")
    parser.add_argument("--limit", type=int, default=0, help="只处理前N个文件；0表示全部")
    parser.add_argument("--resume", action="store_true", help="跳过已在JSONL输出中出现的approval_no")
    parser.add_argument("--dry-run", action="store_true", help="只打印首个项目prompt预览，不请求API")
    parser.add_argument("--no-meta-csv", action="store_true", help="不合并nsfc_results.csv和成果统计CSV")
    parser.add_argument("--nsfc-results-csv", type=Path, default=DEFAULT_NSFC_RESULTS_CSV)
    parser.add_argument("--achievement-stat-csv", type=Path, default=DEFAULT_ACHIEVEMENT_STAT_CSV)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    input_dir: Path = args.input_dir
    output_dir: Path = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    if not input_dir.exists():
        raise FileNotFoundError(f"输入目录不存在：{input_dir}")

    jsonl_path = output_dir / "heritage_llm_coding_results.jsonl"
    csv_path = output_dir / "heritage_llm_coding_results.csv"
    error_path = output_dir / "heritage_llm_coding_errors.jsonl"

    nsfc_meta: dict[str, dict[str, str]] = {}
    achievement_stats: dict[str, dict[str, str]] = {}
    if not args.no_meta_csv:
        nsfc_meta = load_nsfc_results_csv(args.nsfc_results_csv)
        achievement_stats = load_achievement_stat_csv(args.achievement_stat_csv)

    files = sorted(input_dir.glob(args.glob))
    if args.limit and args.limit > 0:
        files = files[: args.limit]

    completed = load_completed_approval_numbers(jsonl_path) if args.resume else set()
    print(f"[INFO] input_dir={input_dir}")
    print(f"[INFO] files={len(files)} model={MODEL_NAME} output={jsonl_path}")
    print(f"[INFO] meta_csv={len(nsfc_meta)} achievement_stats={len(achievement_stats)} resume_completed={len(completed)}")
    print("[INFO] 每个项目将单独创建新的messages并单独请求API，不复用前序项目上下文。")

    if args.dry_run:
        if not files:
            print("[WARN] 没有找到输入文件")
            return
        data = read_project_json(files[0])
        project_text = build_project_text(files[0], data, nsfc_meta, achievement_stats)
        payload = make_payload(project_text)
        print("\n========== SYSTEM_PROMPT PREVIEW ==========\n")
        print(SYSTEM_PROMPT[:5000])
        print("\n========== USER_PROMPT PREVIEW ==========\n")
        print(payload["messages"][1]["content"][:5000])
        print("\n========== PAYLOAD KEYS ==========\n")
        print(json.dumps({k: v for k, v in payload.items() if k != "messages"}, ensure_ascii=False, indent=2))
        return

    run_error_count = 0
    for index, json_path in enumerate(files, 1):
        approval_no = json_path.stem.replace("_llm_ready", "")
        if args.resume and approval_no in completed:
            print(f"[SKIP] {index}/{len(files)} {approval_no} 已完成")
            continue

        print(f"[RUN] {index}/{len(files)} {json_path.name}，新对话/独立请求")
        try:
            project_json = read_project_json(json_path)
            project_text = build_project_text(json_path, project_json, nsfc_meta, achievement_stats)

            # 关键点：每个项目在这里重新创建payload，只有system + 当前项目user两条消息。
            payload = make_payload(project_text)
            raw_content = post_chat_completion(payload)

            if DEBUG_RESPONSE:
                print("[DEBUG_RESPONSE]", raw_content[:DEBUG_RESPONSE_CHARS].replace("\n", " "))

            parsed = extract_first_json_object(raw_content)
            normalized = normalize_output(parsed, json_path)
            append_jsonl(jsonl_path, normalized)
            completed.add(str(normalized.get("approval_no") or approval_no))
            write_csv_from_jsonl(jsonl_path, csv_path)
            print(f"[OK] {approval_no} -> confidence={normalized.get('confidence')}, turn_type={normalized.get('turn_type')}")
        except Exception as exc:
            error_row = {
                "approval_no": approval_no,
                "source_file": str(json_path),
                "error": repr(exc),
                "time": datetime.now().isoformat(timespec="seconds"),
            }
            append_jsonl(error_path, error_row)
            run_error_count += 1
            print(f"[ERROR] {approval_no}: {exc}", file=sys.stderr)

    if jsonl_path.exists():
        write_csv_from_jsonl(jsonl_path, csv_path)
    print(f"[DONE] JSONL: {jsonl_path}")
    print(f"[DONE] CSV:   {csv_path}")
    if error_path.exists():
        if run_error_count:
            print(f"[NOTE] 本轮错误数={run_error_count}，详见：{error_path}")
        else:
            print(f"[NOTE] 存在历史错误日志，本轮未新增错误：{error_path}")


if __name__ == "__main__":
    main()
