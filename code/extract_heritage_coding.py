def append_jsonl(path: Path, row: dict[str, Any]) -> None:
    with path.open("a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def load_completed_approval_numbers(jsonl_path: Path) -> set[str]:
    completed: set[str] = set()
    if not jsonl_path.exists():
        return completed
    with jsonl_path.open("r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            approval_no = str(row.get("approval_no") or "").strip()
            if approval_no:
                completed.add(approval_no)
    return completed


def flatten_for_csv(row: dict[str, Any]) -> dict[str, str]:
    flat: dict[str, str] = {}
    for key, value in row.items():
        if isinstance(value, list):
            flat[key] = "; ".join(str(x) for x in value)
        elif value is None:
            flat[key] = ""
        else:
            flat[key] = str(value)
    return flat


def write_csv_from_jsonl(jsonl_path: Path, csv_path: Path) -> None:
    rows: list[dict[str, Any]] = []
    with jsonl_path.open("r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if line:
                row = json.loads(line)
                approval_no = str(row.get("approval_no") or "").strip() or "unknown"
                source_file = Path(str(row.get("_source_file") or f"{approval_no}_llm_ready.json"))
                rows.append(normalize_output(row, source_file))
    if not rows:
        return

    fieldnames = [row["field"] for row in STRAND_PROMPT_TABLE] + [
        "_source_file",
        "_coded_at",
        "_model",
    ]
    with csv_path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(flatten_for_csv(row))


