def make_payload(project_text: str) -> dict[str, Any]:
    """
    每个项目都创建一组全新的 messages。
    不保存历史消息，不把上一个项目的输出放入下一次请求，从而避免上下文依赖。
    """
    payload: dict[str, Any] = {
        "model": MODEL_NAME,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": USER_PROMPT_TEMPLATE.format(PROJECT_TEXT=project_text)},
        ],
        "max_completion_tokens": MAX_COMPLETION_TOKENS,
    }
    if REASONING_EFFORT:
        payload["reasoning_effort"] = REASONING_EFFORT
    if USE_RESPONSE_FORMAT:
        payload["response_format"] = {"type": "json_object"}
    return payload


def extract_message_content(data: dict[str, Any]) -> str:
    choices = data.get("choices")
    if not isinstance(choices, list) or not choices:
        return ""

    choice = choices[0]
    if not isinstance(choice, dict):
        return ""

    message = choice.get("message")
    if isinstance(message, dict):
        content = message.get("content")
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            parts: list[str] = []
            for part in content:
                if isinstance(part, dict):
                    text = part.get("text") or part.get("content")
                    if isinstance(text, str):
                        parts.append(text)
                elif isinstance(part, str):
                    parts.append(part)
            return "".join(parts)

    text = choice.get("text")
    if isinstance(text, str):
        return text
    return ""


def summarize_api_response(data: dict[str, Any]) -> str:
    choices = data.get("choices")
    choice = choices[0] if isinstance(choices, list) and choices else {}
    message = choice.get("message") if isinstance(choice, dict) else {}
    finish_reason = choice.get("finish_reason") if isinstance(choice, dict) else None
    message_keys = sorted(message.keys()) if isinstance(message, dict) else []
    usage = data.get("usage")
    return f"finish_reason={finish_reason!r}, usage={usage!r}, message_keys={message_keys!r}"


def post_chat_completion(payload: dict[str, Any]) -> str:
    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json",
    }

    last_error: Exception | None = None
    request_payload = dict(payload)
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            body = json.dumps(request_payload, ensure_ascii=False).encode("utf-8")
            request = urllib.request.Request(API_URL, data=body, headers=headers, method="POST")
            with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
                raw = response.read().decode("utf-8", errors="replace")
            data = json.loads(raw)
            content = extract_message_content(data)
            if content.strip():
                return content

            detail = summarize_api_response(data)
            preview = json.dumps(data, ensure_ascii=False)[:1200]
            last_error = RuntimeError(
                "API返回成功但message.content为空；"
                f"{detail}；raw_preview={preview}"
            )
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")
            last_error = RuntimeError(f"HTTP {exc.code}: {detail[:1000]}")
            if (
                exc.code == 400
                and "reasoning_effort" in request_payload
                and "reasoning_effort" in detail
            ):
                request_payload.pop("reasoning_effort", None)
                print("[WARN] 当前API不接受reasoning_effort参数，已移除后重试。", file=sys.stderr)
        except Exception as exc:
            last_error = exc

        print(f"[WARN] API请求失败，第{attempt}/{MAX_RETRIES}次：{last_error}", file=sys.stderr)
        if attempt < MAX_RETRIES:
            time.sleep(min(60, 2 ** attempt + random.random()))

    raise RuntimeError(f"API请求失败，已重试{MAX_RETRIES}次：{last_error}")


def strip_code_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.IGNORECASE)
        text = re.sub(r"\s*```$", "", text)
    return text.strip()


def extract_first_json_object(text: str) -> dict[str, Any]:
    text = strip_code_fence(text)
    if not text:
        raise ValueError("模型响应为空，无法提取JSON对象")
    try:
        obj = json.loads(text)
        if isinstance(obj, dict):
            return obj
    except json.JSONDecodeError:
        pass

    start = text.find("{")
    if start < 0:
        raise ValueError("模型响应中未找到JSON对象")

    depth = 0
    in_string = False
    escape = False
    for i in range(start, len(text)):
        ch = text[i]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
        else:
            if ch == '"':
                in_string = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    obj = json.loads(text[start : i + 1])
                    if not isinstance(obj, dict):
                        raise ValueError("解析到的JSON不是对象")
                    return obj

    raise ValueError("JSON对象括号不完整")


def normalize_output(obj: dict[str, Any], json_path: Path) -> dict[str, Any]:
    expected_fields = [row["field"] for row in STRAND_PROMPT_TABLE]
    normalized: dict[str, Any] = {field: obj.get(field) for field in expected_fields}

    if not normalized.get("approval_no"):
        normalized["approval_no"] = json_path.stem.replace("_llm_ready", "")

    for field in ARRAY_FIELDS:
        value = normalized.get(field)
        if value is None:
            normalized[field] = []
        elif isinstance(value, str):
            normalized[field] = [value]
        elif not isinstance(value, list):
            normalized[field] = [str(value)]

    for field in ALLOWED_LABELS:
        values = normalize_label(field, normalized.get(field))
        if field in ARRAY_FIELDS:
            normalized[field] = values
        elif values:
            normalized[field] = values[0]

    fill_missing_tag_fields(normalized)

    normalized["_source_file"] = str(obj.get("_source_file") or json_path)
    normalized["_coded_at"] = str(obj.get("_coded_at") or datetime.now().isoformat(timespec="seconds"))
    normalized["_model"] = str(obj.get("_model") or MODEL_NAME)
    return normalized


